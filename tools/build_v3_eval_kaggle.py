"""Generate the held-out IXI + external Dallas evaluation Kaggle job."""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRAIN_SOURCES = ["asildoangm/brainage-v3-train-sfcn",
                 "asildoangm/brainage-v3-train-resnet"]
V2_SOURCES = [f"asildoangm/brainage-ixi-train-member-{index}" for index in (1, 2, 3, 4)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--qc-approval", type=Path,
                        default=ROOT / "artifacts/v3/qc/approval.json")
    args = parser.parse_args()
    sources = [f"asildoangm/brainage-v3-merge-{source}"
               for source in ("ixi", "sald", "nimh", "dlbs")]
    target = ROOT / "kaggle/v3_evaluate"
    target.mkdir(parents=True, exist_ok=True)
    files = {name: base64.b64encode((ROOT / name).read_bytes()).decode("ascii") for name in
             ("brainage.py", "v3_model.py", "v3_train.py", "v3_evaluate.py",
              "v3_inputs.py")}
    catalog = base64.b64encode((ROOT / "artifacts/v3/catalog/catalog.csv").read_bytes()).decode("ascii")
    approval = (base64.b64encode(args.qc_approval.read_bytes()).decode("ascii")
                if args.qc_approval.is_file() else "")
    launcher = f'''# Generated by tools/build_v3_eval_kaggle.py.
import base64
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
os.environ["OMP_NUM_THREADS"] = "2"
os.environ["OPENBLAS_NUM_THREADS"] = "2"
os.environ["MPLCONFIGDIR"] = "/tmp/brainage-matplotlib"
subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "numpy==1.26.4", "pandas==2.2.3", "scipy==1.14.1",
                "scikit-learn==1.5.2", "nibabel==5.3.2", "nipype==1.10.0",
                "xlrd==2.0.1", "matplotlib==3.9.2"], check=True)
root = Path("/kaggle/working")
for name, encoded in {files!r}.items():
    (root / name).write_bytes(base64.b64decode(encoded))
(root / "catalog.csv").write_bytes(base64.b64decode({catalog!r}))
if not {bool(approval)!r}:
    raise RuntimeError("Human visual QC approval is required before V3 evaluation")
(root / "qc_approval.json").write_bytes(base64.b64decode({approval!r}))
sys.path.insert(0, str(root))
from v3_inputs import discover_cohorts, verify_qc_approval
inputs = Path("/kaggle/input")
cohorts = discover_cohorts(inputs, ("IXI", "SALD", "NIMH", "DLBS"),
                           root / "catalog.csv")
verify_qc_approval(cohorts, root / "qc_approval.json", root / "catalog.csv")
prepared = Path("/tmp/brainage-v3-prepared")
prepared.mkdir(parents=True, exist_ok=True)
for source, path in cohorts.items():
    (prepared / source.lower()).symlink_to(path)
sfcn_paths = list(inputs.glob("brainage-v3-train-sfcn/training/best.pt"))
resnet_paths = list(inputs.glob("brainage-v3-train-resnet/training/best.pt"))
if len(sfcn_paths) != 1 or len(resnet_paths) != 1:
    raise FileNotFoundError("Missing V3 selected checkpoints")
v2_dir = Path("/tmp/v2-selected")
v2_dir.mkdir(parents=True, exist_ok=True)
for member in (1, 2, 3, 4):
    matches = list(inputs.glob(f"brainage-ixi-train-member-{{member}}/training/best_model.pt"))
    if len(matches) != 1:
        raise FileNotFoundError(f"Missing V2 selected member {{member}}")
    (v2_dir / f"member_{{member}}.pt").symlink_to(matches[0])
subprocess.run([sys.executable, str(root / "v3_evaluate.py"),
                "--catalog", str(root / "catalog.csv"),
                "--prepared-root", str(prepared),
                "--sfcn-checkpoint", str(sfcn_paths[0]),
                "--resnet-checkpoint", str(resnet_paths[0]),
                "--v2-dir", str(v2_dir),
                "--output", str(root / "evaluation")], check=True)
'''
    (target / "run.py").write_text(launcher)
    metadata = {"id": "asildoangm/brainage-v3-evaluate",
                "title": "BrainAGE V3 Locked Evaluation", "code_file": "run.py",
                "language": "python", "kernel_type": "script", "is_private": True,
                "enable_gpu": True, "enable_internet": True,
                "dataset_sources": [], "competition_sources": [], "model_sources": [],
                "kernel_sources": sources + TRAIN_SOURCES + V2_SOURCES}
    (target / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2))
    print(target)
    if not approval:
        print("QC approval absent: generated evaluation job will refuse to run")


if __name__ == "__main__":
    main()
